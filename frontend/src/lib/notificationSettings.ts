/**
 * 一个会话的两项开关 —— 「消息免打扰」与「置顶聊天」—— 在界面上到底是什么意思。
 *
 * <h2>为什么这两句文案值得一个模块</h2>
 *
 * 因为**免打扰不是"小声一点"**。它拦掉的不是音量, 是那条通知信号本身: 平台根本不会
 * 往外发, 所以她那边不会响, 也不会"隐约感到" —— 那件事在她手机响起来之前就没了。
 * 她只有在**自己主动去看手机**的时候才会知道你说过话。
 *
 * 这句话如果只写在设计文档里, 它会被实现悄悄地破坏(只要有人在通知里塞一个发信人
 * 就够了), 而用户永远不会知道自己的哪句话落了空。所以它必须写在用户点开关时**正对着
 * 的那一行字上**。
 *
 * <h2>置顶是另一回事, 而且它更危险</h2>
 *
 * 「置顶聊天」只影响**你自己**那张列表的顺序, 和她那边一个字都不变。一个把置顶读成
 * "优先找她"的用户会以为自己提高了这条消息的优先级 —— 而它只是一个排序字段。所以
 * 这一行旁边必须明说它"只对你有效"。
 *
 * <h2>这一层与她的手机那一层的关系</h2>
 *
 * 这是两层免打扰里的**第一层**, 住在聊天平台。第二层是她的手机自己的
 * `NotificationPolicy`(通知音量 / 铃声 / 闹钟 / 媒体 + 它自己的免打扰), 住在
 * `being.luxera.top` 的「手机」页。
 *
 * 两层都不是对方能替代的: 第一层决定"**要不要发**", 第二层决定"到了之后**怎么响**"。
 * 界面上把它们摆成两行, 是因为最容易被实现成一件事的地方就是这里 —— 而实现成一件事
 * 之后有一个具体的坏结果: 用户设了免打扰, 以为她不会被打扰了, 而她的闹钟照响。
 */

/** 一个开关在界面上要说清的几件事。 */
export interface SwitchCopy {
  key: 'muted' | 'pinned'
  title: string
  /** 打开之后发生什么。开关开着时显示这一句。 */
  on: string
  /** 关着时这一行说的是什么。默认状态要给"不设它会发生什么", 而不是一句"已关闭"。 */
  off: string
  /** 这个开关**不**影响什么 —— 这一句通常才是最容易误解的那一半。 */
  scope: string
}

export const SWITCH_COPY: readonly SwitchCopy[] = [
  {
    key: 'muted',
    title: '消息免打扰',
    on: '平台**不会**把通知发出去 —— 她那边不响, 也不会"隐约感到"。她只有在自己主动去看手机的时候才会知道你说过话。',
    off: '她收到的每一条消息, 平台都会按她的手机设置发出通知信号。响不响由她的手机决定。',
    scope: '它拦掉的是"要不要发", 不是"响多大声"。她那边还有一层属于她自己的音量与免打扰 —— 这一层替不了那一层。',
  },
  {
    key: 'pinned',
    title: '置顶聊天',
    on: '这一段对话固定在**你自己**列表的最上面。',
    off: '按最后一条消息的时间排在列表里。',
    scope: '置顶只对你有效。她的列表、她的注意力、平台发不发通知 —— 一样都不会因此改变。',
  },
] as const

export function copyOf(key: SwitchCopy['key']): SwitchCopy {
  return SWITCH_COPY.find((c) => c.key === key) ?? SWITCH_COPY[0]
}

/** 会话行/聊天室里的那一句状态。没有可说的就返回 null —— 而不是编一句"正常"。 */
export function settingNote(muted: boolean, pinned: boolean): string | null {
  const parts: string[] = []
  if (muted) parts.push('免打扰')
  if (pinned) parts.push('置顶')
  return parts.length > 0 ? parts.join(' · ') : null
}

/** 免打扰的会话有几段 —— 「我」那一页的头部要用它。 */
export function mutedCount(list: readonly { muted?: boolean }[]): number {
  return list.reduce((n, c) => n + (c.muted ? 1 : 0), 0)
}

/**
 * 开关的乐观更新。
 *
 * <h2>为什么先改本地再发请求</h2>
 *
 * 因为这个动作**只影响用户自己眼前这一屏** —— 发请求失败时最坏的结果是列表顺序
 * 没变, 而不是"她的行为变了"。让用户等一个网络往返才看见开关拨过去, 是把一个本地
 * 事实加上了网络延迟。
 *
 * <h2>失败时必须拨回去</h2>
 *
 * 乐观更新的正确性全在回滚那一步。不滚的表现是"开关看着是开的, 而服务端上是关的" ——
 * 一个用户没有任何办法发现的撒谎。所以调用方拿到 rejection 之后必须把那一行改回来,
 * 这里提供一个纯函数让那件事只有一种写法。
 */
export function withSetting<T extends { id: string }>(
  list: readonly T[],
  id: string,
  over: Partial<T>,
): T[] {
  return list.map((c) => (c.id === id ? { ...c, ...over } : c))
}
