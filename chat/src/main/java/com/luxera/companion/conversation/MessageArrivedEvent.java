package com.luxera.companion.conversation;

/**
 * V2.2 §6.1 —— <b>「有一条消息成为了事实, 而且它是发给这个人的」</b>。
 *
 * <h2>它为什么是一个进程内事件, 而不是一次直接的方法调用</h2>
 *
 * <p>因为发通知信号这件事**不是聊天核心的一部分**。会话模块的职责到"消息落库、未读 +1"
 * 为止; "要不要让某个人听见铃声"是客户端形态那一侧的语义(而且它在本仓之外还有第二个
 * 消费者 —— 仓 2 的手机)。写成直接调用, 会话模块就要 import 客户端包, 而客户端包反过来
 * 又要 import 会话包(它要读会话、写消息)—— 一个真实的循环依赖。
 *
 * <p>事件把这个环打开: 会话模块只声明"发生了一件事", 谁关心谁自己订阅。收不到订阅者时
 * 它是一个安静的 no-op, 而不是一次失败 —— 这正是它必须能承受的: {@code bumpOnMessage} 的
 * 调用点包在一个 catch 里(未读计数失败不该挡住消息落库), 一个会抛的通知器会把
 * "聊天室里发一句话"变成一次 500。
 *
 * <h2>为什么一个收件人一个事件, 而不是一个事件带一串收件人</h2>
 *
 * <p>因为免打扰是<b>逐人</b>的(§6.2): 同一个群里, A 免打扰而 B 没有, 那么这一次消息对 A
 * 不发信号、对 B 发。一个事件带一串收件人的话, 订阅方要么自己再拆一遍(那这个事件就没意义
 * 了), 要么就会写出"给所有人发"或者"都不发" —— 而两种都是错的。
 *
 * <p>{@code memberId} 刻意是"人"而不是"账号": 群聊里同一条消息要对每一个非发送者各判一次,
 * 而每个人有自己的一行读状态({@code ConversationReadState})。免打扰就是那一行上的字段。
 *
 * @param conversationId   哪一段会话
 * @param memberId         这次要通知谁(会话参与者 id —— 真人会话里就是他的 userId, Agent
 *                         会话里是它的聊天账号 id)
 * @param senderAccountId  谁发的(聊天账号 id)。**只有 id, 没有姓名、没有正文** —— 事件本身
 *                         就已经是不带内容的了, 于是"通知里不会有正文"这条性质在下游无论
 *                         怎么写都不会被破坏。
 */
public record MessageArrivedEvent(
        String conversationId,
        String memberId,
        String senderAccountId
) {
}
